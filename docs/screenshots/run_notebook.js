const { chromium } = require('playwright');
const OUT = process.env.OUT;
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 2200 }, deviceScaleFactor: 2 });
  page.setDefaultTimeout(120000);
  await page.goto('http://localhost:8899/lab/tree/StarDist_2D_ZeroCostDL4Mic.ipynb');
  await page.waitForSelector('.jp-Notebook', { timeout: 60000 });
  await page.waitForSelector('.jp-Notebook-ExecutionIndicator[data-status="idle"]', { timeout: 120000 }).catch(() => {});
  await page.waitForTimeout(3000);
  await page.screenshot({ path: `${OUT}/01_notebook_opened.png` });
  // Run all cells through the command palette
  await page.keyboard.press('Control+Shift+c');
  await page.keyboard.type('Run All Cells');
  await page.keyboard.press('Enter');
  const form = (title) => page.locator(`.widget-vbox:has(> .widget-html h4:text-is("${title}"))`).first();
  await form('Download a test dataset').waitFor({ state: 'attached', timeout: 300000 });
  await form('Generate prediction(s) from unseen dataset (Big data)').waitFor({ state: 'attached', timeout: 300000 });
  const setText = async (f, name, value) => { await f.scrollIntoViewIfNeeded(); const i = f.locator(`.widget-inline-hbox:has(> label:text-is("${name}")) input`).first(); await i.fill(String(value)); await i.press('Tab'); };
  const setCheck = async (f, name, value) => { await f.scrollIntoViewIfNeeded(); await f.locator(`.widget-checkbox:has(span:text-is("${name}")) input`).first().setChecked(value); };
  const run = async (f, label, waitText, timeout = 600000) => {
    await f.scrollIntoViewIfNeeded();
    await f.locator(`button:has-text("${label}")`).first().click();
    await f.locator(`text=${waitText}`).first().waitFor({ state: 'attached', timeout });
  };
  const shoot = async (f, name) => { await f.scrollIntoViewIfNeeded(); await page.waitForTimeout(800); await f.screenshot({ path: `${OUT}/${name}.png` }); };
  let f = form('Download a test dataset'); await run(f, 'Run', 'Example dataset ready'); await shoot(f, '02_download_dataset');
  f = form('Setting main training parameters');
  await setText(f, 'model_name', 'demo'); await setText(f, 'number_of_epochs', 3);
  await setCheck(f, 'Use_Default_Advanced_Parameters', false); await setText(f, 'number_of_steps', 10); await setText(f, 'patch_size', 256);
  await run(f, 'Run', 'Parameters initiated.'); await shoot(f, '03_training_parameters');
  f = form('Data augmentation'); await run(f, 'Run', 'Data augmentation enabled'); await shoot(f, '04_augmentation');
  f = form('Loading weights from a pre-trained network');
  await setCheck(f, 'Use_pretrained_model', true);
  await f.locator('.widget-dropdown:has(> label:text-is("pretrained_model_choice")) select').selectOption('Model_from_file');
  await setText(f, 'pretrained_model_path', 'pretrained/2D_versatile_fluo');
  await run(f, 'Run', 'will be loaded prior to training'); await shoot(f, '05a_pretrained');
  f = form('Create the model and dataset objects'); await run(f, 'Run', 'Number of steps'); await shoot(f, '05_prepare');
  f = form('Start training'); await run(f, 'Start training', 'Training done', 1200000); await shoot(f, '06_training');
  f = form('Model to evaluate'); await run(f, 'Run', 'will be evaluated');
  f = form('Plot of training errors vs. epoch number'); await run(f, 'Show', 'Training loss', 120000).catch(()=>{}); await page.waitForTimeout(2000); await shoot(f, '07_loss_curves');
  f = form('Error mapping and quality metrics estimation'); await run(f, 'Run', 'Quality control report written'); await page.waitForTimeout(2000); await shoot(f, '08_quality_control');
  f = form('Export your model into the BioImage Model Zoo format');
  await setText(f, 'Trained_model_name', 'StarDist2D demo'); await setText(f, 'Trained_model_authors', '[Guillaume Jacquemet]');
  await run(f, 'Export', 'The model was exported'); await shoot(f, '09_bioimage_export');
  f = form('Generate prediction(s) from unseen dataset');
  await setText(f, 'Data_folder', 'data/Stardist/Test - Images'); await setText(f, 'Results_folder', 'results');
  await run(f, 'Predict', 'Predictions completed'); await page.waitForTimeout(2000); await shoot(f, '10_predictions');
  await browser.close();
  console.log('done');
})().catch(e => { console.error('FAILED', e.message); process.exit(1); });
